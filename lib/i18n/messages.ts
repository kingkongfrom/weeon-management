/** Same keys as `es`; leaf values are localized strings (and shared function shapes). */
type MessageCatalog<T> = {
  [K in keyof T]: T[K] extends (...args: infer A) => string
    ? (...args: A) => string
    : T[K] extends object
      ? MessageCatalog<T[K]>
      : string;
};

export type Messages = MessageCatalog<typeof es>;

